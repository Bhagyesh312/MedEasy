import React from 'react';
import { X, Utensils, AlertTriangle } from 'lucide-react';
import './DietPlanModal.css';

const DietPlanModal = ({ dietPlan, onClose }) => {
  if (!dietPlan) return null;

  const formatContent = (content) => {
    if (!content) return [];

    const lines = content.split('\n');
    const formatted = [];

    lines.forEach((line, index) => {
      const trimmed = line.trim();
      
      // Skip completely empty lines
      if (!trimmed) {
        formatted.push({ type: 'space', key: `space-${index}` });
        return;
      }

      // Main title (starts with ##)
      if (trimmed.match(/^##[^#]/)) {
        formatted.push({ 
          type: 'main-title', 
          content: trimmed.replace(/^##\s*/, '').replace(/\*\*/g, ''),
          key: `title-${index}` 
        });
        return;
      }

      // Day headers (### or starts with Day)
      if (trimmed.match(/^###/) || trimmed.match(/^•\s*Day\s*\d+/i)) {
        const dayText = trimmed.replace(/^###\s*/, '').replace(/^•\s*/, '');
        formatted.push({ 
          type: 'day-header', 
          content: dayText,
          key: `day-${index}` 
        });
        return;
      }

      // Section headers (bold text at start of line or after bullet)
      if (trimmed.match(/^\*\*[^*]+\*\*/)) {
        const headerText = trimmed.replace(/^\*\*/, '').replace(/\*\*.*$/, '');
        const restText = trimmed.replace(/^\*\*[^*]+\*\*\s*/, '');
        formatted.push({ 
          type: 'section-header', 
          content: headerText,
          details: restText,
          key: `section-${index}` 
        });
        return;
      }

      // Bullet points
      if (trimmed.startsWith('•') || trimmed.startsWith('|') || trimmed.startsWith('-')) {
        const bulletText = trimmed.replace(/^[•|\-]\s*/, '');
        
        // Check if it has bold sections
        if (bulletText.includes('**')) {
          formatted.push({ 
            type: 'bullet-rich', 
            content: bulletText,
            key: `bullet-${index}` 
          });
        } else {
          formatted.push({ 
            type: 'bullet', 
            content: bulletText,
            key: `bullet-${index}` 
          });
        }
        return;
      }

      // Horizontal separator
      if (trimmed.match(/^-{3,}$/)) {
        formatted.push({ type: 'separator', key: `sep-${index}` });
        return;
      }

      // Regular paragraph
      if (trimmed.includes('**')) {
        formatted.push({ 
          type: 'paragraph-rich', 
          content: trimmed,
          key: `para-${index}` 
        });
      } else {
        formatted.push({ 
          type: 'paragraph', 
          content: trimmed,
          key: `para-${index}` 
        });
      }
    });

    return formatted;
  };

  const renderRichText = (text) => {
    // Split by ** for bold text
    const parts = text.split(/(\*\*[^*]+\*\*)/g);
    return (
      <>
        {parts.map((part, i) => {
          if (part.startsWith('**') && part.endsWith('**')) {
            return <strong key={i}>{part.slice(2, -2)}</strong>;
          }
          // Handle <br> tags
          if (part.includes('<br>')) {
            return part.split('<br>').map((segment, j) => (
              <React.Fragment key={`${i}-${j}`}>
                {segment}
                {j < part.split('<br>').length - 1 && <br />}
              </React.Fragment>
            ));
          }
          return <span key={i}>{part}</span>;
        })}
      </>
    );
  };

  const formattedContent = formatContent(dietPlan.raw_content);

  return (
    <div className="diet-modal-overlay" onClick={onClose}>
      <div className="diet-modal" onClick={e => e.stopPropagation()}>
        <div className="diet-modal-header">
          <div>
            <h3>
              <Utensils size={20} /> {dietPlan.plan_title || '7-Day Personalized Diet Plan'}
            </h3>
            <p className="diet-modal-subtitle">Generated by AI based on your lab results</p>
          </div>
          <button className="diet-modal-close" onClick={onClose}>
            <X size={20} />
          </button>
        </div>
        
        <div className="diet-modal-content">
          {formattedContent.map((item) => {
            switch (item.type) {
              case 'main-title':
                return (
                  <h2 key={item.key} className="diet-main-title">
                    {item.content}
                  </h2>
                );
              
              case 'day-header':
                return (
                  <h3 key={item.key} className="diet-day-header">
                    {renderRichText(item.content)}
                  </h3>
                );
              
              case 'section-header':
                return (
                  <div key={item.key} className="diet-section">
                    <strong className="diet-section-title">{item.content}</strong>
                    {item.details && <span className="diet-section-details"> {renderRichText(item.details)}</span>}
                  </div>
                );
              
              case 'bullet':
                return (
                  <p key={item.key} className="diet-bullet-simple">
                    • {item.content}
                  </p>
                );
              
              case 'bullet-rich':
                return (
                  <p key={item.key} className="diet-bullet">
                    • {renderRichText(item.content)}
                  </p>
                );
              
              case 'paragraph':
                return (
                  <p key={item.key} className="diet-text">
                    {item.content}
                  </p>
                );
              
              case 'paragraph-rich':
                return (
                  <p key={item.key} className="diet-text">
                    {renderRichText(item.content)}
                  </p>
                );
              
              case 'separator':
                return <hr key={item.key} className="diet-separator" />;
              
              case 'space':
                return <div key={item.key} style={{height: '8px'}} />;
              
              default:
                return null;
            }
          })}

          <div className="diet-disclaimer">
            <AlertTriangle size={16} />
            <p>This diet plan is AI-generated based on your lab results. Always consult with a healthcare professional or registered dietitian before making significant dietary changes.</p>
          </div>
        </div>
      </div>
    </div>
  );
};

export default DietPlanModal;
